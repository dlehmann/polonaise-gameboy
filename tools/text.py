consts = {}
with open(os.path.join(OUT, 'gfx.h')) as f:
    for line in f:
        m = re.match(r'#define (\w+) (\d+)', line)
        if m:
            consts[m.group(1)] = int(m.group(2))

SPECIAL = {'Ä': consts['T_AE'], 'Ö': consts['T_OE'], 'Ü': consts['T_UE'], 'ß': consts['T_SZ']}


def encode(s):
    out = []
    i = 0
    while i < len(s):
        if s.startswith('{}', i):
            out.append(0xfe)
            i += 2
            continue
        ch = s[i]
        if ch == '\n':
            out.append(0xfd)
        elif ch in SPECIAL:
            out.append(SPECIAL[ch])
        else:
            assert 32 <= ord(ch) < 96, (s, ch)
            out.append(consts['T_FONT'] + ord(ch) - 32)
        i += 1
    return out + [0xff]


h = ['/* generated by tools/text.py */', '#ifndef TEXT_H', '#define TEXT_H', '#include <stdint.h>', '',
     '#define TXT_NUM 0xfe', '#define TXT_NL 0xfd', '#define TXT_END 0xff', '']
c = ['/* generated by tools/text.py */', '#include "text.h"', '']
for k, (name, pair) in enumerate(TEXTS.items()):
    for lang, s in enumerate(pair):
        for line in s.split('\n'):
            w = len(line.replace('{}', '0000000' if 'PUNKTE {}' in line or 'SCORE {}' in line else '00'))
            assert w <= WIDTH or name.startswith('ENTRY_HELP') and w <= 20, (name, line, w)
        c.append('static const uint8_t t_%s_%d[] = {%s};' % (name.lower(), lang, ','.join(str(v) for v in encode(s))))
    h.append('#define %s %d' % (name, k))
c.append('')
c.append('const uint8_t * const texts[%d][2] = {' % len(TEXTS))
for name in TEXTS:
    c.append('    {t_%s_0, t_%s_1},' % (name.lower(), name.lower()))
c.append('};')
h += ['', 'extern const uint8_t * const texts[%d][2];' % len(TEXTS), '', '#endif']
with open(os.path.join(OUT, 'text.c'), 'w') as f:
    f.write('\n'.join(c) + '\n')
with open(os.path.join(OUT, 'text.h'), 'w') as f:
    f.write('\n'.join(h) + '\n')
print('%d texts' % len(TEXTS))
