#!/usr/bin/env python3
"""
music.py - the music and the sound effects of Polonaise GB for the Game Boy's sound chip,
after tools/music.py of the C64 version: the disco loop of 16 bars at 120 bpm (four on the
floor, claps on 2 and 4, hi-hats on the off-beats, an octave bass, chord stabs in bars 1..8
and the lead melody in bars 9..16) and the effects.

Channels: 1 the effects, 2 stabs and melody, 3 (wave) the bass, 4 (noise) the drums; an
effect with noise borrows channel 4 while it plays.

Output: gen/music.c, gen/music.h

Usage: tools/music.py <gen dir>
"""
import math
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else 'gen'
A4 = 69

c = ['/* generated by tools/music.py */', '#include "music.h"', '']
h = ['/* generated by tools/music.py */', '#ifndef MUSIC_H', '#define MUSIC_H', '#include <stdint.h>', '']


def table(name, values, typ='uint8_t'):
    c.append('const %s %s[%d] = {' % (typ, name, len(values)))
    for i in range(0, len(values), 16):
        c.append('    ' + ','.join(str(v) for v in values[i:i + 16]) + ',')
    c.append('};')
    h.append('extern const %s %s[%d];' % (typ, name, len(values)))


def note_hz(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def pulse_x(f):
    """The 11 bit frequency value of the pulse channels for f Hz."""
    return max(0, min(2047, int(round(2048 - 131072 / f))))


def wave_x(f):
    return max(0, min(2047, int(round(2048 - 65536 / f))))


# frequencies of the MIDI notes 24..107 (index n - 24)
table('note_pulse', [pulse_x(note_hz(n)) for n in range(24, 108)], 'uint16_t')
table('note_wave', [wave_x(note_hz(n)) for n in range(24, 108)], 'uint16_t')

# ---------------------------------------------------------------- music

STEPS = 256
bass = [0] * STEPS          # 0 none, else MIDI note
drum = [0] * STEPS          # 0 none, 1 kick, 2 kick + clap, 3 closed hat, 4 open hat
v2 = [0] * STEPS            # 0 none, $80 | chord index, else melody note; length in v2len (16ths)
v2len = [0] * STEPS

prog = [(45, [57, 60, 64]), (45, [57, 60, 64]), (50, [57, 62, 65]), (50, [57, 62, 65]),
        (43, [55, 59, 62]), (43, [55, 59, 62]), (48, [55, 60, 64]), (52, [56, 59, 64])] * 2
chords = []
for bar in range(16):
    root, chord = prog[bar]
    s0 = bar * 16
    for beat in range(4):
        s = s0 + beat * 4
        drum[s] = 2 if beat in (1, 3) else 1
        drum[s + 1] = 3
        drum[s + 2] = 4
        drum[s + 3] = 3
    for e in range(8):
        bass[s0 + e * 2] = root - 12 + (12 if e % 2 else 0)
    if bar < 8:
        if chord not in chords:
            chords.append(chord)
        for st in (6, 14):
            v2[s0 + st] = 0x80 | chords.index(chord)
            v2len[s0 + st] = 2

melody = [
    (0, 76, 1), (1, 76, 0.5), (1.5, 74, 0.5), (2, 72, 1), (3, 69, 1),
    (4, 72, 0.5), (4.5, 74, 0.5), (5, 76, 1), (6, 72, 2),
    (8, 74, 1), (9, 74, 0.5), (9.5, 72, 0.5), (10, 69, 1), (11, 65, 1),
    (12, 69, 0.5), (12.5, 72, 0.5), (13, 74, 1), (14, 69, 2),
    (16, 71, 1), (17, 74, 0.5), (17.5, 71, 0.5), (18, 67, 1), (19, 71, 1),
    (20, 72, 0.5), (20.5, 74, 0.5), (21, 76, 1), (22, 79, 2),
    (24, 76, 1), (25, 72, 0.5), (25.5, 69, 0.5), (26, 71, 1), (27, 68, 1),
    (28, 71, 1), (29, 74, 1), (30, 76, 2),
]
for beat, n, length in melody:
    s = 128 + int(beat * 4)
    v2[s] = n
    v2len[s] = max(1, int(length * 4 * 0.9 + 0.5))

table('mus_bass', bass)
table('mus_drum', drum)
table('mus_v2', v2)
table('mus_v2len', v2len)
table('mus_chord', sum(chords, []))

# ---------------------------------------------------------------- effects

# commands of an effect program
VOL, DUTY, NOTE, FREQ, SLIDE, NOISE, OFF, END = 1, 2, 3, 4, 5, 6, 7, 0
effects = {}


def vol(v):
    """The volume envelope (NR12/NR42) for the following notes."""
    return [VOL, v]


def duty(d):
    return [DUTY, d << 6]


def note(n, ticks):
    x = pulse_x(note_hz(n))
    return [NOTE, x >> 8, x & 255, ticks]


def freq(f, ticks):
    x = pulse_x(f)
    return [NOTE, x >> 8, x & 255, ticks]


def slide(f0, f1, ticks):
    a, b = pulse_x(f0), pulse_x(f1)
    return [SLIDE, a >> 8, a & 255, b >> 8, b & 255, ticks]


def noise(level, ticks):
    """Noise: level 0 (highest) .. 7 (lowest)."""
    return [NOISE, (level << 4) | 1, ticks]


def off(ticks):
    return [OFF, ticks]


# the C64 envelopes: a constant level, or a decay from full volume
FULL, DECAY_FAST, DECAY, DECAY_SLOW = 0xa0, 0xf1, 0xf3, 0xf5
effects['TURN'] = vol(0x40) + duty(2) + freq(2200, 1) + off(1)
effects['GO'] = vol(0x90) + duty(2) + slide(700, 1800, 11) + off(3)
effects['DENY'] = vol(0xa0) + duty(2) + freq(220, 2) + freq(232, 3) + off(2)
for k in range(1, 6):
    base = A4 + 3 + 2 * (k - 1)
    effects['CATCH%d' % k] = (vol(0xa1) + noise(1, 1) + vol(DECAY) + duty(2) + note(base, 3) + off(1)
                              + note(base + 7, 13) + off(4))
effects['CATCH_STAR'] = (vol(DECAY_SLOW) + duty(1) + note(A4 + 12, 2) + note(A4 + 16, 2) + note(A4 + 19, 3)
                         + note(A4 + 24, 3) + note(A4 + 28, 2) + off(1) + duty(2) + note(A4 + 7, 4)
                         + note(A4 + 12, 14) + off(4))
effects['FLEE'] = vol(0x80) + duty(2) + slide(1600, 2600, 4) + off(2)
effects['STAR'] = vol(DECAY_FAST) + duty(1) + sum((note(n, 2) for n in (A4 + 19, A4 + 24, A4 + 28, A4 + 31)), []) + \
    note(A4 + 36, 10) + off(3)
effects['STAR_GONE'] = vol(DECAY_FAST) + duty(1) + sum((note(n, 3) for n in (A4 + 31, A4 + 28, A4 + 24)), []) + \
    note(A4 + 19, 10) + off(3)
scratch = vol(0xf0)
for fh in (0x0c, 0x30, 0x08, 0x26, 0x05, 0x1c, 0x04, 0x12):
    scratch += noise(max(0, min(7, int(round(6 - math.log2(fh))))), 2)
effects['CRASH'] = scratch + vol(DECAY_SLOW) + duty(2) + slide(140, 70, 18) + off(6)
effects['EXTRA_LIFE'] = (vol(0xa0) + duty(2) + sum((note(n, 4) for n in (A4 + 3, A4 + 7, A4 + 10, A4 + 15)), [])
                         + note(A4 + 19, 10) + vol(DECAY) + duty(1) + note(A4 + 19, 3) + note(A4 + 22, 3)
                         + note(A4 + 27, 3) + note(A4 + 31, 16) + off(4))
effects['SONG_START'] = (vol(0xa0) + duty(2) + freq(2300, 5) + off(3) + freq(2300, 5) + off(3)
                         + sum((freq(2300 + d, 3) for d in (0, 40, 0, -40, 0, 40, 0)), []) + off(4))
fan = [A4, A4 + 4, A4 + 7, A4 + 12, None, A4 + 7, A4 + 12]
seq = vol(0xa0) + duty(2)
for i, n in enumerate(fan):
    if n is None:
        seq += off(5)
    else:
        seq += note(n, 16 if i == len(fan) - 1 else 4) + off(1)
effects['CLEARED'] = seq + vol(DECAY) + duty(1) + note(A4 + 24, 3) + note(A4 + 28, 3) + note(A4 + 31, 20) + off(4)
effects['GAME_OVER'] = vol(0xa0) + duty(2) + slide(note_hz(A4), 110, 84) + off(20)
effects['PAUSE'] = vol(0xa0) + duty(2) + note(A4 + 7, 4) + note(A4, 4) + off(3)
effects['KEY'] = vol(0x60) + duty(1) + note(A4 + 12, 2) + off(1)

names = list(effects)
# a new effect interrupts the one playing only if it is at least as important
PRIO = {'TURN': 1, 'FLEE': 1, 'GO': 2, 'DENY': 2, 'STAR_GONE': 2, 'CRASH': 4, 'EXTRA_LIFE': 4, 'CLEARED': 5,
        'GAME_OVER': 5}
table('sfx_prio', [0] + [PRIO.get(n, 3) for n in names])
for i, n in enumerate(names):
    h.append('#define SFX_%s %d' % (n, i + 1))
    c.append('static const uint8_t sfx_%d[] = {%s};' % (i, ','.join(str(v) for v in effects[n] + [END])))
c.append('const uint8_t * const sfx_programs[%d] = {%s};' % (len(names), ','.join('sfx_%d' % i
                                                                                 for i in range(len(names)))))
h.append('extern const uint8_t * const sfx_programs[%d];' % len(names))
for k, v in (('VOL', VOL), ('DUTY', DUTY), ('NOTE', NOTE), ('FREQ', FREQ), ('SLIDE', SLIDE), ('NOISE', NOISE),
             ('OFF', OFF), ('END', END)):
    h.append('#define SC_%s %d' % (k, v))
h += ['', '#endif']

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, 'music.c'), 'w') as f:
    f.write('\n'.join(c) + '\n')
with open(os.path.join(OUT, 'music.h'), 'w') as f:
    f.write('\n'.join(h) + '\n')
print('%d effects' % len(names))
